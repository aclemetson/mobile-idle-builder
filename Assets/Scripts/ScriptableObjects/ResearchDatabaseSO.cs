using System;
using UnityEngine;

namespace MobileIdleBuilder
{
    /// <summary>
    /// A research block: one game phase (game_data.json research_blocks). Every ResearchSO names its block.
    /// The start_* fields describe a player who has just reached the block for the first time; the dev console's
    /// `block load` builds a save from them so each phase can be tested on its own.
    /// </summary>
    [Serializable]
    public class ResearchBlock
    {
        public string   id;
        public string   displayName;
        public int      order;
        public float    targetHours;            // time a player running 5 buildings should spend clearing it
        public bool     anchor;                 // the tutorial block: costs are hand-tuned, not derived
        [TextArea] public string description;
        [Header("First arrival")]
        public int      startPrestigeCount;
        public long     startPrestigeCurrencyEarned;
        public long     startEntropy;
        public string[] startPermanentUpgrades = Array.Empty<string>();   // "id:level", the save format
        public string[] startSites             = Array.Empty<string>();
    }

    /// <summary>
    /// Generated by GameDataImporter. Holds all ResearchSO assets in game_data.json order, and the research
    /// blocks (game phases) in block order.
    /// </summary>
    public class ResearchDatabaseSO : ScriptableObject
    {
        public ResearchSO[] allResearch;
        public ResearchBlock[] blocks = Array.Empty<ResearchBlock>();
    }
}
