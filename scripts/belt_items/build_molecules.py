#!/usr/bin/env python3
"""Build Assets/Resources/BeltMolecules.json: every molecule's 3D structure for its belt visual.

    python scripts/belt_items/build_molecules.py            # fetch anything new, write the JSON
    python scripts/belt_items/build_molecules.py --offline  # never touch the network (cache only)

Sources (merged, later wins):
  1. scripts/molecule_icons/structures.json + molecules.json  (the H/C/N/O icon molecules, with hide_h)
  2. scripts/belt_items/molecules_extra.json                   (everything else: PubChem names or inline)
PubChem downloads are cached in scripts/belt_items/structures_extra.json (committed), so the build is
reproducible offline. Every structure's formula is checked against its manifest.

Output coordinates are Angstrom, centred on the heavy atoms; the Unity side (BeltMoleculeData) scales them
to the belt item size. The Blender mockup (mockup_molecules.py) reads the same file.
"""
import json
import pathlib
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICONS = ROOT / "scripts" / "molecule_icons"
HERE = ROOT / "scripts" / "belt_items"
OUT = ROOT / "Assets" / "Resources" / "BeltMolecules.json"
CACHE = HERE / "structures_extra.json"

sys.path.insert(0, str(ICONS))
from fetch_structures import URL, hill_formula, parse_sdf  # noqa: E402


def fetch(name):
    url = URL.format(urllib.parse.quote(name))
    with urllib.request.urlopen(url, timeout=30) as resp:
        cid, atoms, bonds = parse_sdf(resp.read().decode("ascii"))
    time.sleep(0.25)  # PubChem asks for at most 5 requests per second
    return {"cid": cid, "atoms": atoms, "bonds": bonds}


def main(offline):
    icon_manifest = json.loads((ICONS / "molecules.json").read_text(encoding="utf-8"))
    icon_structs = json.loads((ICONS / "structures.json").read_text(encoding="utf-8"))
    extra = json.loads((HERE / "molecules_extra.json").read_text(encoding="utf-8"))
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}

    colors = {**icon_manifest["element_colors"], **extra["element_colors"]}
    radii = {**icon_manifest["element_radii"], **extra["element_radii"]}

    specs = {}
    for mid, spec in icon_manifest["molecules"].items():
        specs[mid] = {"spec": spec, "structure": icon_structs[mid]}
    failed = []
    for mid, spec in extra["molecules"].items():
        if "structure" in spec:
            structure = spec["structure"]
        elif mid in cache:
            structure = cache[mid]
        elif offline:
            print(f"{mid}: not cached and --offline")
            failed.append(mid)
            continue
        else:
            try:
                structure = cache[mid] = fetch(spec["pubchem"])
                print(f"{mid}: fetched CID {structure['cid']}")
            except (urllib.error.URLError, ValueError, IndexError) as exc:
                print(f"{mid}: FAILED {spec['pubchem']}: {exc}")
                failed.append(mid)
                continue
        specs[mid] = {"spec": spec, "structure": structure}

    molecules = []
    for mid in sorted(specs):
        spec, st = specs[mid]["spec"], specs[mid]["structure"]
        formula = hill_formula(a[0] for a in st["atoms"])
        if formula != spec["formula"]:
            print(f"{mid}: FORMULA MISMATCH got {formula}, want {spec['formula']}")
            failed.append(mid)
            continue
        missing = {a[0] for a in st["atoms"]} - set(colors)
        if missing:
            print(f"{mid}: no colour for {sorted(missing)}")
            failed.append(mid)
            continue
        heavy = [a for a in st["atoms"] if a[0] != "H"] or st["atoms"]
        cx, cy, cz = (sum(a[i] for a in heavy) / len(heavy) for i in (1, 2, 3))
        molecules.append({
            "id": mid,
            "hideH": bool(spec.get("hide_h", False)),
            "atoms": [{"e": a[0], "x": round(a[1] - cx, 4), "y": round(a[2] - cy, 4), "z": round(a[3] - cz, 4)}
                      for a in st["atoms"]],
            "bonds": [{"a": b[0], "b": b[1], "o": b[2]} for b in st["bonds"]],
        })

    CACHE.write_text(json.dumps(cache, indent=1) + "\n", encoding="utf-8")
    elements = [{"symbol": s, "color": colors[s], "radius": radii[s]} for s in sorted(colors)]
    OUT.write_text(json.dumps({"_note": "Generated by scripts/belt_items/build_molecules.py; do not edit.",
                               "elements": elements, "molecules": molecules}, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(molecules)} molecules, {len(elements)} elements")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main("--offline" in sys.argv))
